// Regenerates src/components/lucide-icons.ts from the `lucide` npm package (ISC). Usage:
//   bun tools/gen-icons.ts <path-to-node_modules/lucide> [names-file]
// The name list defaults to tools/icon-names.txt (the set the xgen widgets shipped with, so icon props keep working).
import { readFileSync, writeFileSync, existsSync } from "fs";
import { join } from "path";
const lucide = process.argv[2];
const names = readFileSync(process.argv[3] ?? join(import.meta.dir, "icon-names.txt"), "utf8").split(/\s+/).filter(Boolean);
const ver = JSON.parse(readFileSync(join(lucide, "package.json"), "utf8")).version;
const out: string[] = [];
for (const n of names) {
  const f = join(lucide, "dist/esm/icons", `${n}.mjs`);
  if (!existsSync(f)) { console.warn("skip (not in lucide):", n); continue; }
  const node = (await import(f)).default as [string, Record<string, string>][];
  out.push(`  ${JSON.stringify(n)}: ${JSON.stringify(node.map(([t, a]) => [t, a]))},`);
}
writeFileSync(join(import.meta.dir, "../src/components/lucide-icons.ts"),
  `// Generated by tools/gen-icons.ts from lucide ${ver} (ISC, https://lucide.dev). Do not edit by hand.\n` +
  `export const LUCIDE: Record<string, Array<[string, Record<string, string>]>> = {\n${out.join("\n")}\n};\n`);
console.log("icons:", out.length, "lucide", ver);
